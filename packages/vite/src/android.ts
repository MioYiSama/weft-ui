import { execFile } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

/**
 * The Android shell (`native/android`): the Gradle module of the shell and
 * the kernel libraries built by build-core.sh, taken from the workspace
 * until they ship prebuilt with the platform packages.
 */
export const WEFT_ANDROID = fileURLToPath(new URL("../../../native/android", import.meta.url));

/** Asset path of the bytecode in the generated module; the shell loads it from there. */
export const BUNDLE_ASSET = "src/main/assets/weft/bundle.hbc";

/**
 * `weft/settings.gradle.kts`: applied by the settings of the Android
 * template. It includes the generated area as the module `:weft` and the
 * shell as `:weft-android`, referenced relative to the project directory
 * `project` so the project builds wherever the workspace is.
 */
export function settingsFragment(project: string, shell: string): string {
  // On another drive the relative path is absolute; `resolve` keeps absolute paths.
  const path = relative(project, shell).replaceAll("\\", "/");
  return `// Generated by @weft-ui/vite: the app's views and bundle and the Weft shell; every build rewrites it.

include(":weft")
include(":weft-android")
project(":weft-android").projectDir = settingsDir.resolve(${JSON.stringify(path).replaceAll("$", "\\$")})
`;
}

/**
 * `weft/build.gradle.kts`: the generated area as an Android library module
 * in the standard layout: the views (`src/main/kotlin/Generated.kt`) and the
 * bytecode as an asset, on top of the shell, which it exposes to the app.
 */
export function moduleBuild(): string {
  return `// Generated by @weft-ui/vite: the app's views and bundle; every build rewrites it.

plugins {
    id("com.android.library")
    id("org.jetbrains.kotlin.plugin.compose")
}

// Builds rewrite weft/, so the Gradle outputs go to the app's build directory.
layout.buildDirectory.set(rootProject.layout.buildDirectory.dir("weft"))

android {
    namespace = "dev.weft.generated"
    compileSdk = 37
    defaultConfig {
        minSdk = 24
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
    }
}

dependencies {
    api(project(":weft-android"))
}
`;
}

/** The Android SDK named by the environment, `local.properties` of `project`, or the default install location. */
function androidSdk(project: string): string | undefined {
  const fromEnv = process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT;
  if (fromEnv) return fromEnv;
  const properties = join(project, "local.properties");
  if (existsSync(properties)) {
    const dir = /^sdk\.dir=(.*)$/m.exec(readFileSync(properties, "utf8"))?.[1];
    if (dir) return dir.replaceAll("\\:", ":").replaceAll("\\\\", "\\").trim();
  }
  const defaults: Partial<Record<NodeJS.Platform, string>> = {
    darwin: join(homedir(), "Library/Android/sdk"),
    linux: join(homedir(), "Android/Sdk"),
    win32: join(process.env.LOCALAPPDATA ?? join(homedir(), "AppData/Local"), "Android/Sdk"),
  };
  const fallback = defaults[process.platform];
  return fallback && existsSync(fallback) ? fallback : undefined;
}

/**
 * Builds the APK of the Gradle project in `project` with
 * its wrapper: `assembleDebug`, or `assembleRelease` (unsigned unless the
 * project configures signing). The APK is in `project/app/build/outputs/apk/`.
 */
export async function gradleBuild(project: string, release: boolean): Promise<void> {
  const kernel = join(WEFT_ANDROID, "build/jniLibs");
  if (!existsSync(kernel)) {
    throw new Error(`weft: the native kernel for Android is missing (${kernel}); build it with native/android/build-core.sh`);
  }
  const sdk = androidSdk(project);
  if (!sdk) {
    throw new Error(
      "weft: the Android SDK was not found; install it (e.g. with Android Studio) and set ANDROID_HOME, " +
        `or write sdk.dir=<path> to ${join(project, "local.properties")}`,
    );
  }
  const windows = process.platform === "win32";
  const wrapper = join(project, windows ? "gradlew.bat" : "gradlew");
  const args = [release ? "assembleRelease" : "assembleDebug", "--quiet", "--console=plain"];
  try {
    await promisify(execFile)(wrapper, args, {
      cwd: project,
      env: { ...process.env, ANDROID_HOME: sdk },
      maxBuffer: 256 * 1024 * 1024,
      // Batch files only run through a shell.
      shell: windows,
    });
  } catch (cause) {
    const { stdout, stderr, code } = cause as { stdout?: string; stderr?: string; code?: string | number };
    if (code === "ENOENT") throw new Error(`weft: the Gradle wrapper is missing (${wrapper}); restore it from the Android template`);
    const output = `${stdout ?? ""}${stderr ?? ""}`.trim().split(/\r?\n/).slice(-60).join("\n");
    throw new Error(`weft: the Gradle build failed in ${project}\n${output || String(cause)}`);
  }
}
