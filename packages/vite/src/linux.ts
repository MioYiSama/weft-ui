import { execFile } from "node:child_process";
import { relative } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

/**
 * The Linux shell (`native/linux`): its CMake project and the kernel
 * library built by build-core.sh, taken from the workspace until they ship
 * prebuilt with the platform packages.
 */
export const WEFT_LINUX = fileURLToPath(new URL("../../../native/linux", import.meta.url));

/**
 * `weft/CMakeLists.txt`: added by the CMake project of the Linux template.
 * It adds the shell (referenced relative to the generated directory
 * `generated`, so the project builds wherever the workspace is) and builds
 * the generated views (`weft/Generated.cpp`) with the bytecode for the
 * template's `weft_app()` calls.
 */
export function cmakeLists(generated: string, shell: string): string {
  const path = relative(generated, shell).replaceAll("\\", "/");
  return `# Generated by @weft-ui/vite: the app's views and bundle and the Weft shell; every build rewrites it.

add_subdirectory("\${CMAKE_CURRENT_LIST_DIR}/${path}" weft-linux)
weft_views("\${CMAKE_CURRENT_LIST_DIR}/Generated.cpp" "\${CMAKE_CURRENT_LIST_DIR}/bundle.hbc")
`;
}

/**
 * Configures and builds the CMake project in `project` into
 * `project/build/`, with the Debug or Release configuration. The executable
 * is `project/build/app`.
 */
export async function cmakeBuild(project: string, release: boolean): Promise<void> {
  const run = (args: string[]) =>
    promisify(execFile)("cmake", args, { cwd: project, maxBuffer: 256 * 1024 * 1024 });
  try {
    await run(["-S", ".", "-B", "build", `-DCMAKE_BUILD_TYPE=${release ? "Release" : "Debug"}`]);
    await run(["--build", "build", "--parallel"]);
  } catch (cause) {
    const { stdout, stderr, code } = cause as { stdout?: string; stderr?: string; code?: string | number };
    if (code === "ENOENT") {
      throw new Error(
        "weft: cmake not found; install CMake, a C++ compiler and the GTK 4 development packages " +
          "(on Debian and Ubuntu: `sudo apt install build-essential cmake libgtk-4-dev libsoup-3.0-dev libjson-glib-dev`)",
      );
    }
    const output = `${stdout ?? ""}${stderr ?? ""}`.trim().split(/\r?\n/).slice(-60).join("\n");
    throw new Error(`weft: the CMake build failed in ${project}\n${output || String(cause)}`);
  }
}
