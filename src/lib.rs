//! Rust host runtime for Weft UI.
//!
//! A `.weft` file is compiled from `build.rs` with
//! `weft_ui_compiler::compile`, and the generated module is included with
//! [`include_weft!`]. It provides the models as plain structs, the events
//! in an `events` module, and one root component type per component, whose
//! `on_xxx` / `on_xxx_async` methods register event handlers. [`run`] shows
//! the component in a native window: the view runs in a WebView using the
//! Web DOM backend, while the model stays in Rust.
//!
//! ```ignore
//! mod todo_list {
//!     weft_ui::include_weft!("TodoList");
//! }
//!
//! use todo_list::{TodoList, TodoListModel};
//!
//! let app = TodoList::new(TodoListModel::default());
//! app.on_text_changed(|model, e| model.set_draft(e.value));
//! weft_ui::run(app);
//! ```
//!
//! Handlers change the model through the generated `XxxMut` accessors,
//! which record changed field paths. Changes are flushed to the view in one
//! batch per turn of the event loop; the view then updates only the bindings
//! that depend on them.

