//! GTK 4 view backend for Linux, driven by the native kernel's ops.
//!
//! The logic layer uses
//! [`weft_ui_transformer::bridge::remote_module`](crate::bridge::remote_module).
//! This backend generates one `Generated.cpp` for the whole app, compiled
//! against the Linux shell (`native/linux`) in `apps/linux/weft/`. Each
//! template becomes a scope class `S{n}` whose constructor creates its static
//! tree through the shell's element wrappers, keeps the elements with value
//! slots, and applies `set` ops to them. Mount points are registered with
//! regions; the session mounts child scopes.
//!
//! | Element    | Shell wrapper  | Native widget                   |
//! | ---------- | -------------- | ------------------------------- |
//! | `Column`   | `weft::Stack`  | Vertical `WeftStack`            |
//! | `Row`      | `weft::Stack`  | Horizontal `WeftStack`          |
//! | `Text`     | `weft::Text`   | `GtkLabel`                      |
//! | `Button`   | `weft::Button` | `GtkButton`                     |
//! | `Input`    | `weft::Input`  | Controlled `GtkEntry`           |
//! | `Checkbox` | `weft::Checkbox` | Controlled `GtkCheckButton`   |
//! | `Image`    | `weft::Image`  | `GtkPicture`                    |
//!
//! The generated file defines `weft::start_app()`, declared by the shell,
//! which starts the kernel and returns the app's root widget. Layout
//! defaults and controlled editing live in the shell, not in the generated
//! code.

mod cpp;
mod view;

use crate::transform::{Context, OutputFile};
use crate::view::{Template, ValueType, ViewLayout, ViewNodeKind};

use cpp::Code;

/// Path of the generated views, relative to `apps/linux/weft/`.
const VIEWS: &str = "Generated.cpp";

/// Generates the GTK views for the app.
///
/// # Panics
///
/// Panics without a layout in `cx`.
#[must_use]
pub fn transform(cx: &Context<'_>) -> Vec<OutputFile> {
    let layout = cx.layout.expect("the GTK views need the layout");
    vec![OutputFile {
        path: VIEWS.to_owned(),
        contents: generate(layout),
    }]
}

fn generate(layout: &ViewLayout) -> String {
    let mut out = Code::default();
    out.line("// Generated by Weft UI from the app's .weft files; every build rewrites it.");
    out.blank();
    out.line("#include <weft/gtk.hpp>");
    out.blank();
    out.line("#include <memory>");
    out.line("#include <string_view>");
    out.blank();
    out.line("using namespace std::literals;");
    out.blank();
    out.line("namespace {");
    out.blank();
    out.line("/// Hash of the layout; the kernel refuses bundles compiled with another layout.");
    out.line(format!(
        "constexpr uint64_t kLayoutHash = 0x{:016x}ull;",
        layout.hash()
    ));
    for (index, template) in layout.templates().iter().enumerate() {
        out.blank();
        out.line(format!("// {index} {}", template.label));
        out.blank();
        scope(&mut out, index, template);
    }
    out.blank();
    out.line("/// Scope of a `create` op.");
    out.open("std::unique_ptr<weft::Scope> make_scope(uint32_t tpl, uint32_t id, weft::Session &session)");
    out.open("switch (tpl)");
    for index in 0..layout.templates().len() {
        out.line(format!(
            "case {index}: return std::make_unique<S{index}>(id, session);"
        ));
    }
    out.line("default: return nullptr;");
    out.close("");
    out.close("");
    out.blank();
    out.line("}  // namespace");
    out.blank();
    out.line("GtkWidget *weft::start_app() { return Session::start(kLayoutHash, make_scope); }");
    out.finish()
}

/// The scope class `S{index}` of `template`.
fn scope(out: &mut Code, index: usize, template: &Template) {
    out.open(format!("class S{index} final : public weft::Scope"));
    out.access("public");
    let points = if template.points.is_empty() {
        String::new()
    } else {
        format!(", {}", template.points.len())
    };
    out.open(format!(
        "S{index}(uint32_t id, weft::Session &session) : Scope(id, session{points})"
    ));
    view::body(out, template);
    out.close("");
    if template.values.is_empty() {
        out.close(";");
        return;
    }
    out.blank();
    out.open("void apply(uint32_t slot, const weft::ops::Value &value) override");
    out.open("switch (slot)");
    for (slot, value) in template.values.iter().enumerate() {
        let accessor = match value.ty {
            ValueType::Int => "number",
            ValueType::Bool => "boolean",
            ValueType::String => "string",
            ValueType::Color => "color",
        };
        out.line(format!(
            "case {slot}: n{}_->{}(weft::{accessor}(value)); break;",
            value.node,
            view::setter(value.prop),
        ));
    }
    out.close("");
    out.close("");
    out.blank();
    out.access("private");
    for (node, view) in template.nodes.iter().enumerate() {
        let node = u32::try_from(node).expect("template nodes are indexed by u32");
        if !view::is_field(template, node) {
            continue;
        }
        let ViewNodeKind::Element { element, .. } = view.kind else {
            unreachable!("value slots belong to elements");
        };
        for value in template.values.iter().filter(|v| v.node == node) {
            out.line(format!("// {}.{}", element.name(), value.prop));
        }
        out.line(format!("weft::{} *n{node}_;", view::wrapper(element)));
    }
    out.close(";");
}

#[cfg(test)]
mod tests {
    use super::*;
    use weft_ui_parser::MemoryLoader;

    fn cpp(source: &str) -> String {
        let mut loader = MemoryLoader::new();
        loader.insert("App.weft", source);
        let compilation = crate::check(weft_ui_parser::load(&["App.weft"], &mut loader));
        let Some(program) = &compilation.program else {
            panic!("{}", compilation.render_diagnostics());
        };
        generate(&ViewLayout::new(program))
    }

    #[test]
    fn wrappers_inline_constants_before_attaching() {
        let code = cpp(r##"component A() {
                Column(padding = 4, gap = 2, width = 100, height = 80, background = "#abc") {
                    Row(gap = 1) {
                        Text("hello", color = "#12345680", size = 12, bold = true)
                        Button(disabled = true) { Text("button") }
                        Input("", placeholder = "hint", disabled = true)
                        Checkbox(false, disabled = true)
                        Image("image.png", width = 20, height = 30)
                    }
                }
            }"##);
        for expected in [
            "auto &n0 = make<weft::Stack>(weft::Axis::Vertical);",
            "n0.set_padding(4);",
            "n0.set_gap(2);",
            "n0.set_width(100);",
            "n0.set_height(80);",
            "n0.set_background(weft::rgba(0xaabbccffu));\n    roots().add(n0);",
            "auto &n1 = make<weft::Stack>(weft::Axis::Horizontal);",
            "n2.set_value(\"hello\"sv);",
            "n2.set_color(weft::rgba(0x12345680u));",
            "n2.set_size(12);",
            "n2.set_bold(true);\n    n1.children().add(n2);",
            "auto &n3 = make<weft::Button>(nullptr);",
            "n3.set_disabled(true);",
            "n5_ = &make<weft::Input>([this](std::string_view v) { return dispatch(0, v); });",
            "n5_->set_placeholder(\"hint\"sv);",
            "n5_->set_disabled(true);\n    n1.children().add(*n5_);",
            "n6_ = &make<weft::Checkbox>([this](bool v) { return dispatch(1, v); });",
            "n6_->set_disabled(true);",
            "auto &n7 = make<weft::Image>();",
            "n7.set_src(\"image.png\"sv);",
            "n7.set_width(20);",
            "n7.set_height(30);",
            "case 0: n5_->set_value(weft::string(value)); break;",
            "case 1: n6_->set_checked(weft::boolean(value)); break;",
        ] {
            assert!(code.contains(expected), "missing {expected:?}\n{code}");
        }
        assert!(!code.contains("Scope(id, session, "), "{code}");
        assert_eq!(code.matches(" *n").count(), 2, "{code}");
    }

    #[test]
    fn value_slots_share_one_field_and_use_typed_accessors() {
        let code = cpp(
            r#"component A(text: String, size: Int, bold: Bool, color: String) {
                Text(text, size = size, bold = bold, color = color)
            }"#,
        );
        assert_eq!(code.matches("weft::Text *n0_;").count(), 1, "{code}");
        for expected in [
            "// Text.value",
            "// Text.size",
            "// Text.bold",
            "// Text.color",
            "n0_ = &make<weft::Text>();",
            "n0_->set_value(weft::string(value)); break;",
            "n0_->set_size(weft::number(value)); break;",
            "n0_->set_bold(weft::boolean(value)); break;",
            "n0_->set_color(weft::color(value)); break;",
        ] {
            assert!(code.contains(expected), "missing {expected:?}\n{code}");
        }
        assert!(!code.contains("auto &n0"), "{code}");
    }

    #[test]
    fn mount_points_are_registered_in_their_region() {
        let code = cpp(r#"component A(items: String[], on: Bool) {
                Column {
                    if (on) { Text("on") }
                    for (item in items; key = item) { Text(item) }
                }
            }"#);
        for expected in [
            "S0(uint32_t id, weft::Session &session) : Scope(id, session, 2) {",
            "n0.children().point(*this, 0);",
            "n0.children().point(*this, 1);",
            "case 0: return std::make_unique<S0>(id, session);",
        ] {
            assert!(code.contains(expected), "missing {expected:?}\n{code}");
        }
    }
}
