//! SwiftUI backend for iOS and macOS.
//!
//! The logic layer is the remote mode of `weft-ui-codegen-js`, run by the
//! native kernel; this backend generates the view layer the kernel's ops
//! drive: `Generated.swift`, one Swift file for the whole app, compiled into
//! the `WeftApp` package of `apps/<platform>/weft/` against `WeftKit`
//! (`native/apple`). Both platforms get the same code; the few differences
//! (AppKit or UIKit controls) live in WeftKit.
//!
//! Every layout template `n` becomes
//!
//! - `S{n}`, an `@Observable` subclass of `WeftScope` with one property per
//!   value slot (`v{i}`) and mount point (`p{i}`), and the `apply` / `mount`
//!   overrides the session calls for `set` and `branch` / `rows` / `attach`
//!   ops;
//! - `V{n}`, the SwiftUI view of one scope: the static tree with constants
//!   inlined, reading the scope's properties, so SwiftUI only re-renders the
//!   views whose properties changed.
//!
//! The public entry point is `WeftAppView`, which starts the kernel with the
//! bundle and renders the root component.

mod swift;
mod view;

use weft_ui_compiler::codegen::{Codegen, Context, OutputFile};
use weft_ui_compiler::view::{PointKind, Template, ValueType, ViewLayout, ViewNodeKind};

use crate::swift::Code;

/// Path of the generated views, relative to `apps/<platform>/weft/`.
pub const VIEWS: &str = "Generated.swift";

/// View layer of the iOS and macOS backends.
#[derive(Debug, Clone, Copy, Default)]
pub struct SwiftUi;

impl Codegen for SwiftUi {
    /// # Panics
    ///
    /// Panics without a layout in `cx`.
    fn generate(&self, cx: &Context<'_>) -> Vec<OutputFile> {
        let layout = cx.layout.expect("the SwiftUI views need the layout");
        vec![OutputFile {
            path: VIEWS.to_owned(),
            contents: generate(layout),
        }]
    }
}

fn generate(layout: &ViewLayout) -> String {
    let mut out = Code::default();
    out.line("// Generated by Weft UI from the app's .weft files; every build rewrites it.");
    out.blank();
    out.line("import SwiftUI");
    out.line("import WeftKit");
    out.blank();
    out.line("/// The app's kernel session, started on first use with the bundle of this package.");
    out.open("@MainActor private let session = WeftSession(");
    out.line("bytecode: Bundle.module.url(forResource: \"bundle\", withExtension: \"hbc\"),");
    out.line(format!("layoutHash: 0x{:016x},", layout.hash()));
    out.line("make: makeScope");
    out.close(")");
    out.blank();
    out.line("/// Root view of the app.");
    out.open("public struct WeftAppView: View {");
    out.line("public init() {}");
    out.blank();
    out.open("public var body: some View {");
    out.line("WeftRoot(session: session)");
    out.close("}");
    out.close("}");
    out.blank();
    out.line("/// Scope of a `create` op.");
    out.open(
        "@MainActor private func makeScope(template: UInt32, id: UInt32, session: WeftSession) -> WeftScope? {",
    );
    out.line("switch template {");
    for index in 0..layout.templates().len() {
        out.line(format!("case {index}: S{index}(id: id, session: session)"));
    }
    out.line("default: nil");
    out.line("}");
    out.close("}");
    for (index, template) in layout.templates().iter().enumerate() {
        out.blank();
        out.line(format!("// MARK: - {index} {}", template.label));
        out.blank();
        scope(&mut out, index, template);
        out.blank();
        view::view(&mut out, index, template);
    }
    out.finish()
}

/// The scope class `S{index}` of `template`.
fn scope(out: &mut Code, index: usize, template: &Template) {
    out.open(format!(
        "@Observable private final class S{index}: WeftScope {{"
    ));
    for (slot, value) in template.values.iter().enumerate() {
        let ViewNodeKind::Element { element, .. } = &template.nodes[value.node as usize].kind
        else {
            unreachable!("value slots belong to elements");
        };
        out.line(format!("/// {}.{}", element.name(), value.prop));
        let declaration = match value.ty {
            ValueType::Int => "CGFloat = 0",
            ValueType::Bool => "Bool = false",
            ValueType::String => "String = \"\"",
            ValueType::Color => "Color = .clear",
        };
        out.line(format!("var v{slot}: {declaration}"));
    }
    for (point, mount) in template.points.iter().enumerate() {
        let declaration = match &mount.kind {
            PointKind::Branch { .. } | PointKind::Slot => "WeftScope?".to_owned(),
            PointKind::List { template } => format!("[S{}] = []", template.0),
            PointKind::Instance { template } => format!("S{}?", template.0),
        };
        out.line(format!("var p{point}: {declaration}"));
    }
    if !template.values.is_empty() {
        out.blank();
        out.open("override func apply(_ slot: Int, _ value: WeftValue) {");
        out.line("switch slot {");
        for (slot, value) in template.values.iter().enumerate() {
            let accessor = match value.ty {
                ValueType::Int => "length",
                ValueType::Bool => "bool",
                ValueType::String => "string",
                ValueType::Color => "color",
            };
            out.line(format!("case {slot}: v{slot} = value.{accessor}"));
        }
        out.line("default: break");
        out.line("}");
        out.close("}");
    }
    if !template.points.is_empty() {
        out.blank();
        out.open("override func mount(_ point: Int, _ children: [WeftScope]) {");
        out.line("switch point {");
        for (point, mount) in template.points.iter().enumerate() {
            let value = match &mount.kind {
                PointKind::Branch { .. } | PointKind::Slot => "children.first".to_owned(),
                PointKind::List { template } => {
                    format!("children.map {{ $0 as! S{} }}", template.0)
                }
                PointKind::Instance { template } => {
                    format!("children.first.map {{ $0 as! S{} }}", template.0)
                }
            };
            out.line(format!("case {point}: p{point} = {value}"));
        }
        out.line("default: break");
        out.line("}");
        out.close("}");
    }
    out.blank();
    out.line(format!(
        "override var view: AnyView {{ AnyView(V{index}(s: self)) }}"
    ));
    out.close("}");
}

#[cfg(test)]
mod tests {
    use super::*;
    use weft_ui_compiler::MemoryLoader;

    fn swift(source: &str) -> String {
        let mut loader = MemoryLoader::new();
        loader.insert("App.weft", source);
        let compilation = weft_ui_compiler::check("App.weft", &mut loader);
        let Some(program) = &compilation.program else {
            panic!("{}", compilation.render_diagnostics());
        };
        generate(&ViewLayout::new(program))
    }

    #[test]
    fn strings_are_escaped_and_never_interpolated() {
        let code = swift(r#"component A() { Text("say \"hi\" \\(x) \u{7}") }"#);
        assert!(
            code.contains(r#"Text(verbatim: "say \"hi\" \\(x) \u{7}")"#),
            "{code}"
        );
    }
}
