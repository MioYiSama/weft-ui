/// Includes the module generated by `weft_ui_compiler::compile` for the
/// entry file with the given stem, e.g. `include_weft!("TodoList")` for
/// `ui/TodoList.weft`.
#[macro_export]
macro_rules! include_weft {
    ($name:literal) => {
        include!(concat!(env!("OUT_DIR"), "/weft/", $name, ".rs"));
    };
}
