//! Jetpack Compose view backend for Android.
//!
//! The native kernel runs the remote mode of `weft-ui-codegen-js` and drives
//! the views in `Generated.kt`, compiled into the `weft` Android library
//! module against the `dev.weft` shell.
//!
//! Each layout template `n` becomes `S{n}`, a `WeftScope` subclass with Compose
//! state for its value slots and mount points, and `V{n}`, a composable that
//! renders the template's static tree while reading that state. `WeftApp`
//! starts the kernel with the bundle and renders the root component.

mod kotlin;
mod view;

use weft_ui_compiler::codegen::{Codegen, Context, OutputFile};
use weft_ui_compiler::view::{PointKind, Template, ValueType, ViewLayout, ViewNodeKind};

use crate::kotlin::Code;

/// Path of the generated views, relative to `apps/android/weft/`.
pub const VIEWS: &str = "src/main/kotlin/Generated.kt";

/// View layer of the Android backend.
#[derive(Debug, Clone, Copy, Default)]
pub struct Compose;

impl Codegen for Compose {
    /// # Panics
    ///
    /// Panics without a layout in `cx`.
    fn generate(&self, cx: &Context<'_>) -> Vec<OutputFile> {
        let layout = cx.layout.expect("the Compose views need the layout");
        vec![OutputFile {
            path: VIEWS.to_owned(),
            contents: generate(layout),
        }]
    }
}

fn generate(layout: &ViewLayout) -> String {
    let mut out = Code::default();
    out.line("// Generated by Weft UI from the app's .weft files; every build rewrites it.");
    out.blank();
    out.line("package dev.weft.generated");
    out.blank();
    out.line("import androidx.compose.runtime.Composable");
    out.line("import androidx.compose.runtime.getValue");
    out.line("import androidx.compose.runtime.key");
    out.line("import androidx.compose.runtime.mutableFloatStateOf");
    out.line("import androidx.compose.runtime.mutableStateOf");
    out.line("import androidx.compose.runtime.setValue");
    out.line("import androidx.compose.ui.graphics.Color");
    out.line("import dev.weft.*");
    out.blank();
    out.line("/** Root view of the app: starts the kernel with the bundle and renders the root component. */");
    out.line("@Composable");
    out.open("fun WeftApp() {");
    out.line(format_args!(
        "WeftRoot(layoutHash = 0x{:016x}uL, make = ::makeScope)",
        layout.hash()
    ));
    out.close("}");
    out.blank();
    out.line("/** Scope of a `create` op. */");
    out.open("private fun makeScope(template: Int, id: Int, session: WeftSession): WeftScope? = when (template) {");
    for index in 0..layout.templates().len() {
        out.line(format_args!("{index} -> S{index}(id, session)"));
    }
    out.line("else -> null");
    out.close("}");
    for (index, template) in layout.templates().iter().enumerate() {
        out.blank();
        out.line(format_args!("// {index} {}", template.label));
        out.blank();
        scope(&mut out, index, template);
        out.blank();
        view::view(&mut out, index, template);
    }
    out.finish()
}

/// The scope class `S{index}` of `template`.
fn scope(out: &mut Code, index: usize, template: &Template) {
    out.open(format_args!(
        "private class S{index}(id: Int, session: WeftSession) : WeftScope(id, session) {{"
    ));
    for (slot, value) in template.values.iter().enumerate() {
        let ViewNodeKind::Element { element, .. } = &template.nodes[value.node as usize].kind
        else {
            unreachable!("value slots belong to elements");
        };
        out.line(format_args!("/** {}.{} */", element.name(), value.prop));
        let state = match value.ty {
            ValueType::Int => "mutableFloatStateOf(0f)",
            ValueType::Bool => "mutableStateOf(false)",
            ValueType::String => "mutableStateOf(\"\")",
            ValueType::Color => "mutableStateOf(Color.Transparent)",
        };
        out.line(format_args!("var v{slot} by {state}"));
    }
    for (point, mount) in template.points.iter().enumerate() {
        match &mount.kind {
            PointKind::Branch { .. } | PointKind::Slot => out.line(format_args!(
                "var p{point} by mutableStateOf<WeftScope?>(null)"
            )),
            PointKind::List { template } => out.line(format_args!(
                "var p{point} by mutableStateOf<List<S{}>>(emptyList())",
                template.0
            )),
            PointKind::Instance { template } => out.line(format_args!(
                "var p{point} by mutableStateOf<S{}?>(null)",
                template.0
            )),
        }
    }
    if !template.values.is_empty() {
        out.blank();
        out.open("override fun apply(slot: Int, value: WeftValue) {");
        out.open("when (slot) {");
        for (slot, value) in template.values.iter().enumerate() {
            let accessor = match value.ty {
                ValueType::Int => "length",
                ValueType::Bool => "bool",
                ValueType::String => "string",
                ValueType::Color => "color",
            };
            out.line(format_args!("{slot} -> v{slot} = value.{accessor}"));
        }
        out.close("}");
        out.close("}");
    }
    if !template.points.is_empty() {
        out.blank();
        out.open("override fun mount(point: Int, children: List<WeftScope>) {");
        out.open("when (point) {");
        for (point, mount) in template.points.iter().enumerate() {
            match &mount.kind {
                PointKind::Branch { .. } | PointKind::Slot => {
                    out.line(format_args!("{point} -> p{point} = children.firstOrNull()"))
                }
                PointKind::List { template } => out.line(format_args!(
                    "{point} -> p{point} = children.map {{ it as S{} }}",
                    template.0
                )),
                PointKind::Instance { template } => out.line(format_args!(
                    "{point} -> p{point} = children.firstOrNull() as S{}?",
                    template.0
                )),
            }
        }
        out.close("}");
        out.close("}");
    }
    if !template.values.is_empty() || !template.points.is_empty() {
        out.blank();
    }
    out.line("@Composable");
    out.line(format_args!("override fun Content() = V{index}(this)"));
    out.close("}");
}

#[cfg(test)]
mod tests {
    use super::*;
    use weft_ui_compiler::MemoryLoader;

    #[test]
    fn strings_are_escaped_and_never_interpolated() {
        let mut loader = MemoryLoader::new();
        loader.insert(
            "App.weft",
            r#"component A() { Text("say \"hi\" \\ $name \${x} \n\r\t\u{8}\u{7} café") }"#,
        );
        let compilation = weft_ui_compiler::check("App.weft", &mut loader);
        let Some(program) = &compilation.program else {
            panic!("{}", compilation.render_diagnostics());
        };
        let code = generate(&ViewLayout::new(program));
        assert!(
            code.contains(r#"WeftText("say \"hi\" \\ \$name \${x} \n\r\t\b\u0007 café")"#),
            "{code}"
        );
    }
}
